# Логистическая модель роста числа пользователей сервиса
# Практическая работа 1, тема 1.1 "Основы моделирования"
# Вариант 6: a = 2.1, K = 75 000, N0 = 6 000, T = 40
import numpy as np
import matplotlib.pyplot as plt

# блок параметров (вариант 6) — единственное место, которое меняется
a = 2.1          # коэффициент прироста
K = 75_000.0     # ёмкость рынка
N0 = 6_000.0     # начальное число пользователей
T = 40           # горизонт моделирования, месяцев

N = np.zeros(T + 1)   # массив результатов: N[t] — пользователи к концу месяца t
N[0] = N0

# рекуррентное соотношение логистической модели
for t in range(T):
    N[t + 1] = N[t] + a * N[t] * (1.0 - N[t] / K)

# вывод контрольных значений для сверки с Excel и ручным расчётом
for t in (0, 1, 6, 12, 18, T):
    print(f"t = {t:2d}  N = {N[t]:10.1f}")
hit = np.nonzero(N >= 0.95 * K)[0]
print("t* (первый месяц достижения 0,95*K):", int(hit[0]) if hit.size else "не достигнут")
print(f"ручная проверка N(1): {N0:.0f} + {a}*{N0:.0f}*(1 - {N0:.0f}/{K:.0f}) = {N[1]:.1f}")

# график динамики
plt.figure(figsize=(8, 4.5))
plt.plot(range(T + 1), N, marker="o", ms=3)
plt.axhline(K, color="gray", ls="--", lw=1, label="Ёмкость рынка K")
plt.xlabel("Месяц t")
plt.ylabel("Число пользователей N(t)")
plt.title("Логистическая модель роста пользователей")
plt.legend()
plt.grid(alpha=0.3)
plt.tight_layout()
plt.show()
